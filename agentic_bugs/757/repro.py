#!/usr/bin/env python3
"""Probe issue #1689 without contacting an LLM or an OpenAI-compatible server.

The issue's 400 response was generated by vLLM.  This local double verifies that
the pinned smolagents code only propagates/wraps that upstream response; it
cannot create the server-side "Expected 2 output messages" condition itself.
"""

from __future__ import annotations

from types import SimpleNamespace

from smolagents import CodeAgent, OpenAIServerModel
from smolagents.utils import AgentGenerationError


UPSTREAM_MESSAGE = "Expected 2 output messages (reasoning and final), but got 64."


class VLLMRejection(Exception):
    """A deterministic stand-in for the 400 reply recorded in the issue."""

    def __str__(self) -> str:
        return (
            "Error code: 400 - {'object': 'error', 'message': "
            f"'{UPSTREAM_MESSAGE}', 'type': 'BadRequestError', "
            "'param': None, 'code': 400}"
        )


class LocalOnlyOpenAIModel(OpenAIServerModel):
    def create_client(self):
        def reject(**_kwargs):
            raise VLLMRejection()

        return SimpleNamespace(chat=SimpleNamespace(completions=SimpleNamespace(create=reject)))


def main() -> None:
    # No socket is opened: create() above always raises before a request could exist.
    agent = CodeAgent(tools=[], model=LocalOnlyOpenAIModel(model_id="local-vllm"), max_steps=1)
    try:
        agent.run("Return a short answer.")
    except AgentGenerationError as error:
        observed = str(error)
        assert UPSTREAM_MESSAGE in observed, observed
        assert isinstance(error.__cause__, VLLMRejection), type(error.__cause__)
        print("NOT_REPRODUCED: smolagents wrapped the injected upstream vLLM 400; it did not create it.")
        return
    raise AssertionError("Expected the local fake vLLM response to be wrapped by CodeAgent")


if __name__ == "__main__":
    main()
