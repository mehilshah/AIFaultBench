#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV_DIR="$ROOT/.venv"

if [ ! -d "$VENV_DIR" ]; then
  python3 -m venv "$VENV_DIR"
fi

"$VENV_DIR/bin/python" -m pip install --upgrade --quiet pip setuptools wheel
"$VENV_DIR/bin/python" -m pip install --quiet --disable-pip-version-check -r "$ROOT/requirements.txt"
